"""Export everything ZHA knows about devices and entities into a file."""

from __future__ import annotations

import json
import logging
import os
from typing import Any

from homeassistant.config_entries import ConfigEntryState
from homeassistant.core import HomeAssistant
from homeassistant.exceptions import HomeAssistantError
from homeassistant.helpers import (
    area_registry as ar,
    device_registry as dr,
    entity_registry as er,
)
from homeassistant.util import dt as dt_util

from .const import (
    COORDINATOR_BACKUP_FILE,
    EXPORT_DIR,
    EXPORT_LATEST,
    RADIO_TO_Z2M_ADAPTER,
    Z2M_SNIPPET_FILE,
    ZHA_DOMAIN,
    normalize_ieee,
)
from .store import MigrationStore

_LOGGER = logging.getLogger(__name__)


class ExportError(HomeAssistantError):
    """Raised when the export cannot be created."""

    def __init__(self, key: str) -> None:
        super().__init__(key)
        self.key = key


def _json_safe(value: Any) -> Any:
    """Convert arbitrary state attributes into plain JSON types."""
    return json.loads(json.dumps(value, default=str))


def _entity_friendly_name(
    entry: er.RegistryEntry, device: dr.DeviceEntry, state_name: str | None
) -> str:
    if state_name:
        return state_name
    if entry.name:
        return entry.name
    device_name = device.name_by_user or device.name or ""
    if entry.original_name:
        return f"{device_name} {entry.original_name}".strip()
    return device_name


def _export_entity(
    hass: HomeAssistant, entry: er.RegistryEntry, device: dr.DeviceEntry
) -> dict[str, Any]:
    state = hass.states.get(entry.entity_id)
    attributes = _json_safe(dict(state.attributes)) if state else {}
    return {
        "entity_id": entry.entity_id,
        "unique_id": entry.unique_id,
        "domain": entry.domain,
        "platform": entry.platform,
        "name": entry.name,
        "original_name": entry.original_name,
        "friendly_name": _entity_friendly_name(
            entry, device, attributes.get("friendly_name")
        ),
        "icon": entry.icon,
        "original_icon": entry.original_icon,
        "area_id": entry.area_id,
        "labels": sorted(entry.labels),
        "aliases": sorted(entry.aliases),
        "device_class": entry.device_class,
        "original_device_class": entry.original_device_class
        or attributes.get("device_class"),
        "unit_of_measurement": entry.unit_of_measurement
        or attributes.get("unit_of_measurement"),
        "translation_key": entry.translation_key,
        "entity_category": entry.entity_category,
        "disabled_by": entry.disabled_by,
        "hidden_by": entry.hidden_by,
        "options": _json_safe({k: dict(v) for k, v in entry.options.items()}),
        "state": state.state if state else None,
        "attributes": attributes,
    }


async def _async_network_backup(hass: HomeAssistant) -> dict[str, Any] | None:
    """Return the ZHA network as Open Coordinator Backup, if ZHA can provide it."""
    try:
        from homeassistant.components.zha import api as zha_api  # noqa: PLC0415
    except ImportError:
        return None

    for func_name in (
        "async_get_active_network_settings",
        "async_get_last_network_settings",
    ):
        func = getattr(zha_api, func_name, None)
        if func is None:
            continue
        try:
            backup = await func(hass)
            if backup is not None:
                return _json_safe(backup.as_open_coordinator_json())
        except Exception:  # noqa: BLE001 - the ZHA API is internal and may change
            _LOGGER.debug("Could not read ZHA network via %s", func_name, exc_info=True)
    return None


def _z2m_snippet(backup: dict[str, Any], adapter: str | None, port: str | None) -> str:
    """Build the Zigbee2MQTT configuration needed to take over the ZHA network."""

    def hex_list(value: str) -> str:
        return "[" + ", ".join(f"0x{value[i:i + 2]}" for i in range(0, len(value), 2)) + "]"

    lines = [
        "# Generated by ZHA → Zigbee2MQTT Migration",
        "# Only use this with the SAME coordinator and only while ZHA is disabled!",
        "serial:",
        f"  port: {port or '<your coordinator port>'}",
        f"  adapter: {adapter or '<your adapter type>'}",
        "advanced:",
        f"  pan_id: 0x{backup['pan_id']}",
        f"  ext_pan_id: {hex_list(backup['extended_pan_id'])}",
        f"  network_key: {hex_list(backup['network_key']['key'])}",
        f"  channel: {backup['channel']}",
        "",
    ]
    return "\n".join(lines)


def _write_files(directory: str, files: dict[str, str]) -> None:
    os.makedirs(directory, exist_ok=True)
    for name, content in files.items():
        with open(os.path.join(directory, name), "w", encoding="utf-8") as handle:
            handle.write(content)


async def async_export_zha(hass: HomeAssistant, store: MigrationStore) -> dict[str, Any]:
    """Snapshot all ZHA devices/entities, write the files and update the store."""
    zha_entries = hass.config_entries.async_entries(ZHA_DOMAIN)
    if not zha_entries:
        raise ExportError("no_zha")

    dev_reg = dr.async_get(hass)
    ent_reg = er.async_get(hass)
    area_reg = ar.async_get(hass)

    devices: dict[str, dict[str, Any]] = {}
    for zha_entry in zha_entries:
        for device in dr.async_entries_for_config_entry(dev_reg, zha_entry.entry_id):
            ieee = next(
                (
                    normalize_ieee(ident)
                    for domain, ident in device.identifiers
                    if domain == ZHA_DOMAIN
                ),
                "",
            )
            if not ieee:
                continue
            entities = [
                _export_entity(hass, entry, device)
                for entry in er.async_entries_for_device(
                    ent_reg, device.id, include_disabled_entities=True
                )
                if entry.platform == ZHA_DOMAIN
            ]
            area = area_reg.async_get_area(device.area_id) if device.area_id else None
            devices[ieee] = {
                "ieee": ieee,
                "device_id": device.id,
                "name": device.name,
                "name_by_user": device.name_by_user,
                "manufacturer": device.manufacturer,
                "model": device.model,
                "sw_version": device.sw_version,
                "area_id": device.area_id,
                "area_name": area.name if area else None,
                "labels": sorted(device.labels),
                "disabled_by": device.disabled_by,
                "via_device_id": device.via_device_id,
                "entities": entities,
            }

    if not devices:
        raise ExportError("no_zha_devices")

    main_entry = zha_entries[0]
    radio_type = main_entry.data.get("radio_type")
    port = (main_entry.data.get("device") or {}).get("path")
    adapter = RADIO_TO_Z2M_ADAPTER.get(radio_type) if radio_type else None

    network_backup = None
    if main_entry.state is ConfigEntryState.LOADED:
        network_backup = await _async_network_backup(hass)

    now = dt_util.now()
    directory = hass.config.path(EXPORT_DIR)
    export_name = f"zha_export_{now.strftime('%Y%m%d_%H%M%S')}.json"

    export: dict[str, Any] = {
        "exported_at": now.isoformat(),
        "export_file": os.path.join(directory, export_name),
        "ha_version": hass.config.as_dict().get("version"),
        "zha": {
            "entry_id": main_entry.entry_id,
            "title": main_entry.title,
            "radio_type": radio_type,
            "port": port,
            "z2m_adapter": adapter,
            "network_backup_available": network_backup is not None,
        },
        "devices": devices,
    }

    content = json.dumps(export, indent=2, ensure_ascii=False)
    files = {export_name: content, EXPORT_LATEST: content}
    if network_backup is not None:
        files[COORDINATOR_BACKUP_FILE] = json.dumps(network_backup, indent=2)
        try:
            files[Z2M_SNIPPET_FILE] = _z2m_snippet(network_backup, adapter, port)
        except (KeyError, TypeError):
            _LOGGER.debug("Network backup has an unexpected format", exc_info=True)

    await hass.async_add_executor_job(_write_files, directory, files)

    store.set_export(export)
    await store.async_save()
    return export
